def write_table(values: dict, path: Path):
    lines = [".. Generated by docs/figures/redmapper_dr11/make_all.py: do not edit.", "",
             ".. list-table::", "   :header-rows: 1", "   :widths: 44 14 42", "",
             "   * - Quantity", "     - DR11 (rema)", "     - Literature"]
    for label, key, spec, lit in ROWS:
        v = values.get(key)
        try:
            text = fmt(v, spec)
        except (TypeError, ValueError, IndexError):
            text = "—"
        lines += [f"   * - {label}", f"     - {text}", f"     - {lit or '—'}"]
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path.name}")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--force", action="store_true", help="redo the products of prepare.py")
    p.add_argument("--only", nargs="*", help="run only these fig_* scripts")
    p.add_argument("--table", action="store_true", help="only rewrite values.rst")
    args = p.parse_args(argv)
    env = {**os.environ, "JAX_PLATFORMS": os.environ.get("JAX_PLATFORMS", "cpu"), "PYTHONUNBUFFERED": "1"}
    sys.path.insert(0, str(HERE))
    if not args.table:
        steps = [["prepare.py"] + (["--force"] if args.force else [])] + \
                [[f"{s}.py"] for s in (args.only or SCRIPTS)]
        failed = []
        for step in steps:
            t0 = time.time()
            print(f"--- {step[0]}", flush=True)
            r = subprocess.run([sys.executable, str(HERE / step[0]), *step[1:]], env=env, cwd=HERE)
            print(f"--- {step[0]}: {'ok' if r.returncode == 0 else 'FAILED'} ({time.time() - t0:.0f} s)", flush=True)
            if r.returncode:
                failed.append(step[0])
                if step[0] == "prepare.py":
                    sys.exit(1)
        if failed:
            print("failed:", failed)
    from common import VALUES_FILE

    values = json.loads(VALUES_FILE.read_text()) if VALUES_FILE.exists() else {}
    write_table(values, HERE / "values.rst")


if __name__ == "__main__":
    main()
