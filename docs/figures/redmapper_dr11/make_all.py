"""Make every figure of docs/redmapper_dr11.rst and its table of numbers.

    python docs/figures/redmapper_dr11/make_all.py [--force] [--only fig_redshifts ...] [--table]

Runs prepare.py (``--force`` redoes its products), then each fig_*.py script in its own process,
then writes values.rst (DR11 numbers next to the literature) from the values.json that the
scripts fill. ``--table`` only rewrites values.rst.
"""

