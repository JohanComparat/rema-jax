SCRIPTS = ["fig_redsequence", "fig_redshifts", "fig_richness", "fig_abundance", "fig_centering", "fig_external",
           "fig_members"]


def fmt(v, spec):
    if v is None:
        return "—"
    if callable(spec):
        return spec(v)
    return format(v, spec)


def pct(v):
    return f"{100 * v:.1f}%"


def pair(i, spec=".2f"):
    return lambda v: format(v[i], spec)


